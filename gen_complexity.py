"""
gen_complexity.py -- rebuilds COMPLEXITY.md from the `Time:` / `Space:` lines in every docstring.

Run:   python gen_complexity.py        (then COMPLEXITY.md is up to date)
"""

import ast
from pathlib import Path

HERE = Path(__file__).parent
FILES = [("ds.py", "Linked list, Stack, Max-heap, Circular queue"), ("engine.py", "rules"),
         ("bot.py", "probability + bot"), ("bot_lab.py", "presentation experiments"), ("gui.py", "pygame UI"),
         ("webapi.py", "browser bridge (Pyodide)")]

INTRO = """# Complexity reference - every function

Generated by `gen_complexity.py` from the `Time:` / `Space:` lines in each function's docstring (a unit
test fails if any function is missing them).  Notation: **n** = items in a data structure, **h** = cards in a
hand (<= 9), **k** = cards in a play (<= 2), **c** = candidate bot moves (<= 10), **K** = `TOP_K` = 3,
**p** = plays on the pile, **R** = rounds, **T** = turns per round, **W** = bot memory window,
**M** = matches in a lab experiment, **S** = distinct look-ahead states.

Because h, k, c and K are tiny constants in this game, several `O(h^2)`-style bounds are "constant in
practice" - but they are stated in terms of the variable so the *analysis* is the real one.
"""


def field(doc, label):
    """Text after `label` ("Time:" or "Space:") in a docstring, or '?' if the line is missing.

    Time:  O(len(doc))
    Space: O(1)
    """
    for line in doc.splitlines():
        line = line.strip()
        if line.startswith(label):
            return line[len(label):].strip().replace("|", "/")
    return "?"


def collect(tree):
    """Every function in a module as (qualified name, time, space), in source order.

    Time:  O(nodes in the tree)
    Space: O(functions)
    """
    rows = []

    def walk(node, prefix):
        """Recurse through classes and functions, remembering the dotted name.

        Time:  O(nodes below `node`)
        Space: O(depth)
        """
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.ClassDef):
                walk(child, prefix + child.name + ".")
            elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                doc = ast.get_docstring(child) or ""
                rows.append((prefix + child.name, field(doc, "Time:"), field(doc, "Space:")))
                walk(child, prefix + child.name + ".")
            else:
                walk(child, prefix)

    walk(tree, "")
    return rows


def main():
    """Write COMPLEXITY.md next to this script and report how many functions it lists.

    Time:  O(total source size)
    Space: O(functions)
    """
    out, total = [INTRO], 0
    for name, label in FILES:
        rows = collect(ast.parse((HERE / name).read_text(encoding="utf-8")))
        total += len(rows)
        out.append("**%s (%s)**\n" % (name, label))
        out.append("| Function | Time | Space |\n|---|---|---|")
        out.extend("| `%s` | %s | %s |" % row for row in rows)
        out.append("")
    (HERE / "COMPLEXITY.md").write_text("\n".join(out), encoding="utf-8")
    print("COMPLEXITY.md written: %d functions" % total)


if __name__ == "__main__":
    main()
